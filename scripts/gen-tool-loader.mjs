/**
 * Generates the tool loader from the registry plus what is actually on disk.
 *
 * Two reasons this is generated rather than hand-written:
 *
 * 1. A bundler cannot split a fully dynamic `import(`@/tools/${slug}`)` — the
 *    path has to be a literal for each tool to become its own chunk. Writing
 *    a hundred literals by hand is how a hundred and one appear later.
 * 2. The bench ships in batches. Listing only the slugs whose directory
 *    exists lets the registry name a tool before it is built, and the index
 *    mark it as pending, instead of linking to a page that throws.
 *
 * Usage: node scripts/gen-tool-loader.mjs   (runs automatically via prebuild)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { TOOLS } = await import(join(root, 'content/tools/registry.ts'));

const built = TOOLS.filter((tool) =>
  existsSync(join(root, 'src/tools', tool.slug, 'index.tsx'))
).map((tool) => tool.slug);

const banner = `/* Generated by scripts/gen-tool-loader.mjs — do not edit by hand. */\n`;

const loader = `${banner}'use client';

import dynamic from 'next/dynamic';
import type { ComponentType } from 'react';
import type { ToolProps } from './types';

/** Slug → lazily loaded implementation. One chunk per tool. */
export const TOOL_COMPONENTS: Record<string, ComponentType<ToolProps>> = {
${built.map((slug) => `  '${slug}': dynamic(() => import('./${slug}'), { ssr: false }),`).join('\n')}
};
`;

const manifest = `${banner}
/** Slugs with an implementation on disk, in registry order. */
export const BUILT_TOOLS: readonly string[] = [
${built.map((slug) => `  '${slug}',`).join('\n')}
];

export const BUILT = new Set(BUILT_TOOLS);
`;

const write = (path, next) => {
  const full = join(root, path);
  const prev = existsSync(full) ? readFileSync(full, 'utf8') : '';
  if (prev === next) return false;
  writeFileSync(full, next);
  return true;
};

const a = write('src/tools/loader.generated.ts', loader);
const b = write('src/tools/built.generated.ts', manifest);
console.log(
  `tool loader: ${built.length}/${TOOLS.length} implemented${a || b ? ' (rewritten)' : ' (unchanged)'}`
);
